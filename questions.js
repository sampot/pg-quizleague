/** @param {number} match @param {number} [seed] */
export function pickMatchQuestions(match, seed = 0) {
  const start = ((match - 1) * 7 + seed * 3) % QUESTIONS.length;
  return Array.from({ length: QUESTIONS_PER_MATCH }, (_, i) => {
    const q = QUESTIONS[(start + i) % QUESTIONS.length];
    return { ...q, choices: [...q.choices] };
  });
}

export function validateQuestion(q) {
  return (
    typeof q.text === "string" &&
    Array.isArray(q.choices) &&
    q.choices.length === 4 &&
    Number.isInteger(q.answer) &&
    q.answer >= 0 &&
    q.answer < 4
  );
}
